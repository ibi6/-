export const THEME_STORAGE_KEY = 'payloadx-theme'

export function getTheme(id: ThemeId): ThemeDef {
  return themes.find((t) => t.id === id) ?? themes[0]
}

export function applyThemeVars(id: ThemeId) {
  const theme = getTheme(id)
  const root = document.documentElement
  root.setAttribute('data-theme', id)
  Object.entries(theme.vars).forEach(([k, v]) => {
    root.style.setProperty(k, v)
  })
}

export function getPalette(id: ThemeId): ThemePalette {
  const v = getTheme(id).vars
  return {
    accent: v['--accent'],
    accent2: v['--accent-2'],
    accentDeep: v['--accent-deep'],
    secondary: v['--secondary'],
    chart: [
      v['--chart-1'],
      v['--chart-2'],
      v['--chart-3'],
      v['--chart-4'],
      v['--chart-5'],
      v['--chart-6'],
      v['--chart-7'],
    ],
  }
}

export function loadStoredTheme(): ThemeId {
  try {
    const raw = localStorage.getItem(THEME_STORAGE_KEY) as ThemeId | null
    if (raw && themes.some((t) => t.id === raw)) return raw
  } catch {
    /* ignore */
  }
  return 'blue'
}
